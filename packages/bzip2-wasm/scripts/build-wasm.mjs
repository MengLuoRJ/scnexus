import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const root = fileURLToPath(new URL('../', import.meta.url))
const image =
  'mirror.gcr.io/emscripten/emsdk:4.0.23@sha256:86537645c51e44899812d29820ee3b64b96c321ebb2aba4416a04ceeb1bcde62'
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
mkdirSync(new URL('../.build', import.meta.url), { recursive: true })

const command = [
  'set -eu',
  'emcc --version',
  'emcc native/decoder.c native/bzip2-1.0.8/bzlib.c native/bzip2-1.0.8/compress.c native/bzip2-1.0.8/blocksort.c native/bzip2-1.0.8/decompress.c native/bzip2-1.0.8/huffman.c native/bzip2-1.0.8/crctable.c native/bzip2-1.0.8/randtable.c -Inative/bzip2-1.0.8 -DBZ_NO_STDIO -O3 -flto --no-entry -sSTANDALONE_WASM=1 -sFILESYSTEM=0 -sMALLOC=emmalloc -sABORTING_MALLOC=0 -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=16777216 -sMAXIMUM_MEMORY=536870912 -sSTACK_SIZE=65536 -sEXPORTED_FUNCTIONS=\'["_malloc","_free","_bzip2_create","_bzip2_step","_bzip2_consumed","_bzip2_produced","_bzip2_destroy"]\' -Wl,--strip-all -o .build/bzip2.wasm',
].join(' && ')
const result = spawnSync(
  'docker',
  [
    'run',
    '--rm',
    '--platform',
    'linux/amd64',
    '--network',
    'none',
    '--mount',
    `type=bind,source=${root},target=/work`,
    '-w',
    '/work',
    image,
    'sh',
    '-c',
    command,
  ],
  { stdio: 'inherit' },
)
if (result.error) throw result.error
if (result.status !== 0) throw new Error(`WASM compiler exited with ${result.status}`)
const wasm = readFileSync(new URL('../.build/bzip2.wasm', import.meta.url))
const module = new WebAssembly.Module(wasm)
if (WebAssembly.Module.imports(module).length !== 0)
  throw new Error('Decoder must not import host functions')
const hash = sha256(wasm)
writeFileSync(
  new URL('../src/wasm.generated.ts', import.meta.url),
  `// Generated by pnpm build:wasm; do not edit. libbz2 license: ../LICENSE.libbz2\n// WASM SHA-256: ${hash}\nexport const wasmBase64 =\n  '${wasm.toString('base64')}'\n`,
)
console.log(`WASM: ${wasm.length} bytes; SHA-256: ${hash}`)
